#!/usr/bin/env bun
// Assembles Phosmith's Hugging Face Space from services/segment and
// services/masking (see services/space/main.py for why they share one Space)
// and, with `deploy`, uploads it.
//
//   bun scripts/space.mjs build [dir]   assemble into dir (default .cache/space-build)
//   bun scripts/space.mjs deploy        assemble and upload to SPACE_ID
//
// Upload uses the huggingface_hub login on this machine (a token with repo
// write access); files on the Space that the build no longer has are deleted.

import path from 'node:path'
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'

const ROOT = path.resolve(import.meta.dir, '..')
const SPACE_ID = process.env.SPACE_ID || 'ArAnirudh/Phosmith'
const [command = 'build', outArg] = process.argv.slice(2)
const OUT = path.resolve(outArg || path.join(ROOT, '.cache', 'space-build'))
const log = (msg) => console.log(`[space] ${msg}`)

// Destination name → source, relative to the repo root.
const FILES = {
    'main.py': 'services/space/main.py',
    'Dockerfile': 'services/space/Dockerfile',
    'README.md': 'services/space/README.md',
    'segment_service.py': 'services/segment/main.py',
    'depth_service.py': 'services/masking/main.py',
    'preload_lama.py': 'services/segment/preload_models.py',
    'preload_depth.py': 'services/masking/preload_models.py',
}

// One requirements file for both services: every package once, first spec wins.
const mergeRequirements = async () => {
    const seen = new Map()
    for (const file of ['services/segment/requirements.txt', 'services/masking/requirements.txt']) {
        for (const raw of (await readFile(path.join(ROOT, file), 'utf8')).split('\n')) {
            const line = raw.trim()
            if (!line || line.startsWith('#')) continue
            const name = line.split(/[<>=!~\[;\s]/)[0].toLowerCase()
            if (!seen.has(name)) seen.set(name, line)
        }
    }
    return `# Generated by scripts/space.mjs from services/segment and services/masking.\n${[...seen.values()].join('\n')}\n`
}

const build = async () => {
    await rm(OUT, { recursive: true, force: true })
    await mkdir(OUT, { recursive: true })
    for (const [dest, src] of Object.entries(FILES)) await cp(path.join(ROOT, src), path.join(OUT, dest))
    await writeFile(path.join(OUT, 'requirements.txt'), await mergeRequirements())
    log(`assembled ${Object.keys(FILES).length + 1} files in ${path.relative(ROOT, OUT)}`)
}

const python = () => {
    const venv = path.join(ROOT, 'services/segment/.venv/bin/python')
    return existsSync(venv) ? venv : 'python3'
}

const deploy = async () => {
    await build()
    const script = `
import sys
from huggingface_hub import HfApi
api = HfApi()
repo, folder = sys.argv[1], sys.argv[2]
local = {"main.py", "Dockerfile", "README.md", "segment_service.py", "depth_service.py", "preload_lama.py", "preload_depth.py", "requirements.txt"}
remote = set(api.list_repo_files(repo, repo_type="space"))
stale = sorted(remote - local - {".gitattributes"})
info = api.upload_folder(repo_id=repo, repo_type="space", folder_path=folder,
                         delete_patterns=stale or None,
                         commit_message="Deploy from Phosmith services/segment + services/masking")
print("uploaded", sorted(local), "deleted", stale, "commit", getattr(info, "oid", "")[:10])
`
    const proc = Bun.spawnSync([python(), '-c', script, SPACE_ID, OUT], { stdout: 'inherit', stderr: 'inherit' })
    if (proc.exitCode !== 0) process.exit(proc.exitCode)
    log(`pushed to https://huggingface.co/spaces/${SPACE_ID} — it rebuilds now`)
}

if (command === 'build') await build()
else if (command === 'deploy') await deploy()
else {
    console.error('usage: bun scripts/space.mjs build [dir] | deploy')
    process.exit(1)
}
